function aPlantilla([nombre, dias, paradas]: CiudadCruda): RouteTemplate {
  return {
    id: `ruta-${nombre
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")}`,
    name: `${nombre} en ${dias} ${dias === 1 ? "día" : "días"}`,
    region: nombre,
    summary: `Los lugares más conocidos de ${nombre}, repartidos en ${dias} ${dias === 1 ? "día" : "días"}.`,
    dayCount: dias,
    stops: paradas.map(
      ([name, category, latitude, longitude, minutos, dia]): RouteTemplateStop => ({
        name,
        category,
        coordinates: { latitude, longitude },
        shortDescription: "",
        recommendedDurationMinutes: minutos,
        dayIndex: dia,
      }),
    ),
  };
}

export const CATALOGO_CIUDADES: RouteTemplate[] = CIUDADES.map(aPlantilla);
